export const ADMISSIONS_SNAPSHOT = '20261107';
export const ADMISSION_RECORDS: AdmissionRecord[] = [];
export const UNIVERSITY_PROGRAMS: UniversityProgram[] = [];
export const ADMISSION_COVERAGE: AdmissionCoverage[] = [];

// The database is authoritative. Load this dated reference snapshot only when
// the database request fails; large datasets never enter the initial JS bundle.
export async function loadAdmissionFallback() {
  const [records, programs, coverage] = await Promise.all(
    ['records', 'programs', 'coverage'].map(async kind => {
      const response = await fetch(`/data/admissions/${kind}-${ADMISSIONS_SNAPSHOT}.json`);
      if (!response.ok) throw new Error('Admission reference snapshot unavailable');
      const data = await response.json();
      if (!Array.isArray(data)) throw new Error('Invalid admission reference snapshot');
      return data;
    })
  );
  ADMISSION_RECORDS.splice(0, ADMISSION_RECORDS.length, ...records);
  UNIVERSITY_PROGRAMS.splice(0, UNIVERSITY_PROGRAMS.length, ...programs);
  ADMISSION_COVERAGE.splice(0, ADMISSION_COVERAGE.length, ...coverage);
}
